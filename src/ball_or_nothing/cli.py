"""Command line entry point for demos, verification, and RTP tuning."""

from __future__ import annotations

import argparse
import sys

from . import config as cfg
from . import par
from .spinner import spin


def _cmd_par(_args: argparse.Namespace) -> int:
    sheet = par.par_sheet()

    print(f"{cfg.WORKING_NAME}  ({cfg.GAME_ID})")
    print(f"  {cfg.NUM_REELS} reels x {cfg.NUM_ROWS} rows, {len(cfg.PAYLINES)} paylines")
    print()
    print(f"  target RTP           {cfg.TARGET_RTP:.4f}")
    print(f"  exact RTP            {sheet.rtp:.6f}   (base {sheet.base_rtp:.4f} + bonus {sheet.bonus_rtp:.4f})")
    print(f"  BALLGAME trigger     {sheet.trigger_rate:.6f}  (1 in {1 / sheet.trigger_rate:.0f})")
    print()
    print(f"  top prize (5 BALL)   {cfg.Paytable().five_ball:.2f}x")
    print(f"  max multiplier       {sheet.max_multiplier}x")
    print(f"  MAX WIN              {sheet.max_win:.0f}x   (wincap {cfg.WINCAP:.0f}x)")
    print()
    print(f"  THE BYPASS          removed - Stake books cannot branch mid-round")
    print()
    print(f"  house edge           {1 - sheet.rtp:.6f}")
    return 0


def _cmd_verify(args: argparse.Namespace) -> int:
    expected = par.closed_form_rtp()
    result = par.monte_carlo(args.spins, seed=0)

    print(f"simulating {args.spins:,} rounds...")
    print()
    print(f"  closed-form RTP      {expected:.6f}")
    print(f"  monte carlo RTP      {result.mean_payout:.6f}  (+-{result.standard_error:.6f})")
    print(f"  hit rate             {result.hit_rate:.6f}")
    print(f"  BALLGAMEs            {result.bonus_hits}  (1 in {args.spins / max(result.bonus_hits, 1):.0f})")
    print(f"  biggest win seen     {result.max_seen:.2f}x")
    print()

    if result.agrees_with(expected, sigmas=5.0):
        print("  PASS: simulation agrees with the closed form.")
        return 0

    print("  FAIL: simulation disagrees with the closed form.")
    return 1


def _cmd_modes(_args: argparse.Namespace) -> int:
    """Print the volatility ladder. This is the authority for any published mode numbers."""
    sheet = par.par_sheet()
    print(f"{cfg.WORKING_NAME} - the volatility ladder")
    print("chosen at BET TIME, so every rung stays fully pre-computed")
    print()
    print(f"  {'mode':<10} {'RTP':>11} {'top prize':>11} {'max win':>11}  character")
    print("  " + "-" * 74)
    for s in par.mode_sheets():
        print(f"  {s.label:<10} {s.rtp:>11.7f} {s.top_prize:>10.1f}x {s.max_win:>10,.0f}x  {s.blurb}")
    print()
    print(f"  every rung is solved independently to {cfg.TARGET_RTP}")
    print("  no mode shares a constant with another")
    print()
    print(f"  default (if the client sends no mode): {cfg.DEFAULT_MODE}")
    print(f"  machine: {cfg.NUM_REELS} reels x {cfg.NUM_ROWS} rows, {len(cfg.PAYLINES)} paylines")
    print(f"  shipped BALL rung: RTP {sheet.rtp:.6f}, top prize {cfg.Paytable().five_ball:.2f}x, "
          f"max win {sheet.max_win:,.0f}x")
    return 0


def _cmd_emit_modes(_args: argparse.Namespace) -> int:
    """Regenerate frontend/modes.js from the solved ladder.

    The demo must play the numbers the closed form produced. Generating the JS rather than
    hand-copying it is what keeps the two machines from drifting.
    """
    import json
    from pathlib import Path

    modes = {}
    for mode in cfg.MODES.values():
        table = par.solve_mode(mode)
        modes[mode.name] = {
            "name": mode.name,
            "label": mode.label,
            "blurb": mode.blurb,
            "wincap": mode.wincap,
            "weights": cfg.mode_reels(mode),
            "freeWeights": cfg.mode_free_reels(mode),
            "paytable": {f"{k[0]}:{k[1]}": round(v, 6) for k, v in table.as_table().items()},
        }

    target = Path(__file__).resolve().parents[2] / "frontend" / "modes.js"
    target.write_text(
        "// GENERATED by `python -m ball_or_nothing.cli emit-modes` - do not hand-edit.\n"
        "//\n"
        "// The volatility ladder, solved by the Python core and emitted here so the demo\n"
        "// plays the exact numbers the closed form produced. Hand-copying these would let\n"
        "// the two machines drift, which is the defect this file exists to prevent.\n\n"
        f"export const MODES = {json.dumps(modes, indent=2)};\n\n"
        f"export const DEFAULT_MODE = {json.dumps(cfg.DEFAULT_MODE)};\n",
        encoding="utf-8",
    )

    print(f"wrote {target}")
    for name, m in modes.items():
        print(f"  {m['label']:<10} wincap {m['wincap']:>9,.0f}x  top {m['paytable']['5:BALL']:>8.2f}x")
    return 0


def _cmd_demo(args: argparse.Namespace) -> int:
    for i in range(args.count):
        outcome = spin(i)
        rows = [" ".join(f"{s:<5}" for s in reel) for reel in outcome.board]
        if outcome.bonus:
            verdict = f"BALLGAME x{outcome.bonus.start_spins} -> {outcome.payout_multiplier:.2f}x"
        elif outcome.is_win:
            verdict = f"WIN {outcome.payout_multiplier:.2f}x"
        else:
            verdict = "nothing"
        print(f"  round {i:>4}  |{rows[0]}|  {verdict}")
        for row in rows[1:]:
            print(f"             |{row}|")
    return 0


def _cmd_tune(args: argparse.Namespace) -> int:
    top = par.solve_five_ball_for_rtp(args.target)
    current = par.par_sheet()

    print(f"  current 5-BALL  {cfg.Paytable().five_ball:.4f}x")
    print(f"  current RTP     {current.rtp:.6f}")
    print()
    print(f"  solved 5-BALL   {top:.4f}x  for RTP {args.target}")
    print()
    print("  set this in config.py:")
    print(f"    five_ball: float = {top:.4f}")
    print(f"    five_wild: float = {top:.4f}")
    print()
    print(f"  resulting max win  {par.max_win(cfg.Paytable(five_ball=top, five_wild=top)):.0f}x")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="ball_or_nothing", description="BALL OR NOTHING - math tools")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("par", help="print the exact PAR sheet")
    p.set_defaults(func=_cmd_par)

    p = sub.add_parser("verify", help="closed-form vs monte carlo")
    p.add_argument("spins", type=int, nargs="?", default=60_000)
    p.set_defaults(func=_cmd_verify)

    p = sub.add_parser("demo", help="print a few sample rounds")
    p.add_argument("count", type=int, nargs="?", default=3)
    p.set_defaults(func=_cmd_demo)

    p = sub.add_parser("modes", help="print the volatility ladder")
    p.set_defaults(func=_cmd_modes)

    p = sub.add_parser("emit-modes", help="regenerate frontend/modes.js from the solved ladder")
    p.set_defaults(func=_cmd_emit_modes)

    p = sub.add_parser("tune", help="solve the top prize for a target RTP")
    p.add_argument("target", type=float, nargs="?", default=cfg.TARGET_RTP)
    p.set_defaults(func=_cmd_tune)

    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    sys.exit(main())
